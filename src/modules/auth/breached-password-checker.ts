import crypto from 'crypto';
import { resilientFetch } from '../../utils/resilient-fetch';

// Проверка пароля на "Have I Been Pwned" Pwned Passwords (k-anonymity range API, NIST 800-63B
// прямо рекомендует сверку с базой утекших паролей). Сам пароль — и даже полный хеш пароля —
// НИКОГДА не уходит по сети: наружу отправляются только первые 5 hex-символов SHA-1(пароль)
// ("prefix"), сервис в ответ отдаёт ВСЕ известные ему хеши с таким префиксом (обычно
// несколько сотен строк) — совпадение по оставшимся символам ("suffix") ищем локально.
// Сервер HIBP физически не может узнать, какой конкретно пароль проверялся — только то, что
// проверялся какой-то пароль с этим 5-символьным префиксом хеша, чего достаточно для k-анонимности.
const HIBP_RANGE_URL = 'https://api.pwnedpasswords.com/range/';
const REQUEST_TIMEOUT_MS = 3000;

// Тот же класс bypass'а, что уже есть у email.queue.ts для Redis (isTestEnv) — но здесь
// он обязателен, а не просто "не поднимать лишний сервис ради теста": 'password123' —
// пароль-фикстура, зашитый буквально везде в test/helpers.ts и большинстве спеков этого
// проекта, и он реально числится в утечках HIBP. Без этого bypass'а вся интеграционная
// сюита (не unit — там isPasswordBreached замокан отдельно, см. auth.service.unit.spec.ts)
// стабильно ловила бы честный 400 PASSWORD_BREACHED на каждой тестовой регистрации: живой
// прогон 2026-09-02 воспроизвёл это ровно так — 102 упавших теста разом, "verification
// token not found" (register() отклонён ДО создания пользователя). Это не баг проверки —
// она отработала правильно, просто тестовому окружению здесь вообще не место обращаться
// к стороннему HTTP API за настоящим вердиктом.
const isTestEnv = process.env.NODE_ENV === 'test';

export async function isPasswordBreached(password: string): Promise<boolean> {
  if (isTestEnv) {
    return false;
  }

  const sha1 = crypto.createHash('sha1').update(password).digest('hex').toUpperCase();
  const prefix = sha1.slice(0, 5);
  const suffix = sha1.slice(5);

  try {
    // GET, без побочных эффектов — идемпотентен, ретрай безопасен. retries: 1 (не больше) —
    // это путь регистрации/смены/сброса пароля, пользователь ждёт ответа синхронно; один
    // повторный запрос покрывает единичный транзиентный сбой, не превращая fail-open проверку
    // в многосекундную задержку самого auth-потока при затяжной недоступности HIBP.
    const response = await resilientFetch(`${HIBP_RANGE_URL}${prefix}`, {
      timeoutMs: REQUEST_TIMEOUT_MS,
      retries: 1,
      // Add-Padding — официальная рекомендация HIBP: сервис дополняет ответ случайным
      // количеством "мусорных" строк фиксированного вида, чтобы размер ответа не выдавал
      // (по количеству реальных совпадений) даже примерную популярность конкретного пароля.
      headers: { 'Add-Padding': 'true' },
    });

    if (!response.ok) {
      // Fail-open, осознанно: сторонний сервис ответил ошибкой (недоступен, rate-limit,
      // временный сбой) — это НЕ повод заблокировать пользователю регистрацию/смену пароля.
      // Проверка на утечки — это defense-in-depth поверх argon2id+pepper, не единственный
      // рубеж; отказ HIBP не должен превращать несвязанный сторонний сбой в отказ auth-потока
      // всего приложения. Fail-closed здесь означало бы: HIBP лёг → никто не может
      // зарегистрироваться/сменить пароль, пока сторонний сервис не поднимется — асимметрично
      // хуже, чем изредка пропустить проверку на утечки.
      return false;
    }

    const body = await response.text();
    // Строки вида "SUFFIX:COUNT", разделитель — \r\n. Сравниваем именно с частью до ':',
    // не startsWith() на всю строку — иначе достаточно совпадения по первым символам чужого
    // suffix, а не полного 35-символьного хвоста хеша.
    return body.split(/\r?\n/).some(line => line.split(':')[0] === suffix);
  } catch {
    // Таймаут, сетевая ошибка или исчерпанный ретрай внутри resilientFetch — тот же
    // fail-open принцип, что и для !response.ok.
    return false;
  }
}
